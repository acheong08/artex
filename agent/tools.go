// addOneGoal adds an open goal node to the exploration graph and links it to the task
// root (origin fact, rel spawns). Origin is t.worker (default "system"): "goals" for
// the decomposer and "human" for goals added by the main agent. setGoals wakes the
// planner once after the entire batch; this function only persists the goal.
func (t *ToolSet) addOneGoal(it goalItem) (int64, error) {
	text := strings.TrimSpace(it.Text)
	if text == "" {
		return 0, fmt.Errorf("text cannot be empty")
	}
	payload := map[string]any{"text": text}
	if vc := strings.TrimSpace(it.VulnClass); vc != "" {
		payload["vulnclass"] = vc
	}
	origin := t.worker
	if origin == "" {
		origin = "system"
	}
	id, err := t.ts.AddNode(db.KindGoal, payload, 0, "open", origin, nil)
	if err != nil {
		return 0, err
	}
	if of, _ := t.ts.OriginFactID(); of > 0 && id > 0 {
		_ = t.ts.Link(of, db.RelSpawns, id) // goals descend from the task root (origin fact)
	}
	return id, nil
}

// setGoals adds exploration goal nodes to this task. It is used both by the goal
// decomposer and by the main agent at runtime; the same managed tool can have its
// description/schema edited and its binding selected per agent in the web UI.
func (t *ToolSet) setGoals() actool.CoreTool {
	return writeTool("set_goals",
		"Add exploration goals to **this task**. A goal is a final deliverable/verifiable outcome, not an attack step or reconnaissance action.\n"+
			"★Prefer batch submission: put multiple goals in the goals array and submit them in one call. Returned IDs match it in length and order (failed items have id=0; see errors for details). For a single goal, omit goals and provide text at the top level.\n"+
			"vulnclass is optional: use it for the relevant vulnerability class (e.g. SQLi/IDOR), and leave it empty for business-logic goals. The system determines and marks whether a goal is met; this tool only adds goals.",
		obj(map[string]any{
			"goals":     map[string]any{"type": "array", "description": "Preferred: goals to add, processed in order. Each item has text (required, one independent and verifiable final goal) and optional vulnclass. Returned IDs match this array in length and order.", "items": map[string]any{"type": "object"}},
			"text":      str("[Single goal] One independent, verifiable final goal"),
			"vulnclass": str("[Single goal] Corresponding vulnerability class, if explicit (e.g. SQLi/IDOR); leave empty for business-logic goals"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.ts == nil {
				return actool.Errorf("set_goals is unavailable: ExplorationStore is not initialized"), nil
			}
			var a struct {
				Goals    []goalItem `json:"goals"`
				goalItem            // Single-item mode: top-level text/vulnclass.
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Goals) > 0
			items := a.Goals
			if !batch {
				items = []goalItem{a.goalItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			var addedTexts []string
			for i, it := range items {
				id, err := t.addOneGoal(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				addedTexts = append(addedTexts, strings.TrimSpace(it.Text))
			}
			if len(addedTexts) > 0 {
				// Wake the planner once per batch. Prefer notifyGoal, which records one
				// "Human added N goals: …" trigger rather than one per goal. The decomposer
				// and workers have no such callback and fall back to notify; the decomposer
				// has no notify callback during round 0, before the planner starts.
				switch {
				case t.notifyGoal != nil:
					t.notifyGoal(addedTexts)
				case t.notify != nil:
					t.notify()
				}
				// Goals added by the main agent resume completed/paused tasks (the terminal
				// gate swallows ordinary notifications, so an explicit resume is needed).
				// Only mainagent wires this callback; it is nil for the decomposer/workers.
				if t.resumeTask != nil {
					t.resumeTask()
				}
			}

			if !batch { // Single item: preserve the original return shape.
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("goal added: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

